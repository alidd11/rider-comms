// Future non-Google route-rendering boundary. Research only; no network requests.
// An OSM basemap must never render a Google Routes/Directions response.
const APPROVED_ENGINES = new Set(['valhalla', 'osrm']);
export const MAX_ROUTE_POINTS = 10_000;

export function parseOpenRoute(input) {
  if (!input || typeof input !== 'object' || Array.isArray(input)) {
    throw new TypeError('Route must be an object');
  }
  const { provenance, coordinates, distanceMeters, durationSeconds } = input;
  if (!provenance || typeof provenance !== 'object' || Array.isArray(provenance)
      || !APPROVED_ENGINES.has(provenance.engine)
      || provenance.mapData !== 'openstreetmap') {
    throw new Error('Route needs an approved open-data engine and OpenStreetMap provenance');
  }
  if (!Array.isArray(coordinates) || coordinates.length < 2 || coordinates.length > MAX_ROUTE_POINTS) {
    throw new RangeError('Route must have 2–10000 points');
  }
  if (!Number.isFinite(distanceMeters) || distanceMeters <= 0 || distanceMeters > 10_000_000
      || !Number.isFinite(durationSeconds) || durationSeconds <= 0 || durationSeconds > 7 * 24 * 3600) {
    throw new RangeError('Route metrics must be finite positive values in range');
  }
  // This contract intentionally excludes traffic, speed limits, toll assessments,
  // lane instructions and all other metadata until authoritative sources exist.
  for (const key of ['traffic', 'trafficAware', 'speedLimits', 'tolls', 'lanes', 'googlePlaceId']) {
    if (Object.hasOwn(input, key)) throw new Error('Unverified route metadata is not permitted: ' + key);
  }
  const points = coordinates.map((point) => {
    if (!Array.isArray(point) || point.length !== 2
        || !Number.isFinite(point[0]) || !Number.isFinite(point[1])
        || point[0] < -180 || point[0] > 180 || point[1] < -90 || point[1] > 90) {
      throw new RangeError('Route coordinate must be a valid [longitude, latitude] pair');
    }
    return [...point];
  });
  return {
    type: 'Feature',
    properties: {
      source: 'open-data',
      engine: provenance.engine,
      mapData: 'openstreetmap',
      distanceMeters,
      durationSeconds,
      trafficAvailable: false,
      navigationReady: false, // Requires instruction/maneuver/road quality validation first.
    },
    geometry: { type: 'LineString', coordinates: points },
  };
}

// A synthetic shape for checking overlay rendering and persistence after a
// style switch. It is not road-matched, not generated by a routing engine and
// must never be displayed as an actual ride route.
export function illustrativeLine() {
  return {
    type: 'Feature',
    properties: {
      source: 'synthetic-demo',
      navigationReady: false,
      description: 'Illustrative path — not riding directions',
    },
    geometry: {
      type: 'LineString',
      coordinates: [
        [-0.1405, 51.5071],
        [-0.1370, 51.5082],
        [-0.1334, 51.5095],
        [-0.1298, 51.5090],
      ],
    },
  };
}
